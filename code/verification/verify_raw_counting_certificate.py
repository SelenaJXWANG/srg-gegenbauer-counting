#!/usr/bin/env python3
"""Verify a raw SRG nonexistence identity without elimination or any solver.

Python standard library only. This checker deliberately uses a different
enumeration: append all binary adjacency profiles to a labelled template.
Graph isomorphism orbits are generated by adjacent transpositions, not by
the permutation/host-embedding enumerators in the other two implementations.
Only rational spectra, degrees 1 and 2, and levels <= 6 are supported here.
"""
import argparse
from collections import Counter
from fractions import Fraction as Q
from functools import lru_cache
from hashlib import sha256
from itertools import combinations, product
import json
from math import factorial, isqrt
from pathlib import Path


def require(condition, message):
    if not condition:
        raise ValueError(message)


def bits_of(n, code):
    return format(code, f'0{n*(n-1)//2}b') if n > 1 else ''


def read_graph(n, bits):
    require(type(n) is int and 1 <= n <= 6, 'Unsupported graph size')
    require(len(bits) == n*(n-1)//2 and set(bits) <= {'0', '1'}, 'Invalid bits')
    return int(bits, 2) if bits else 0


def adjacent(n, code, i, j):
    if i == j:
        return 0
    if i > j:
        i, j = j, i
    index = i*(2*n-i-1)//2 + j-i-1
    return (code >> (n*(n-1)//2 - index-1)) & 1


def append_vertex(n, code, profile):
    require(len(profile) == n, 'Wrong appended profile')
    result = 0
    for i in range(n+1):
        for j in range(i+1, n+1):
            result = 2*result + (profile[i] if j == n else adjacent(n, code, i, j))
    return result


@lru_cache(None)
def universe(n):
    """Full orbit partition under generators (0 1), (1 2), ... ."""
    edge_list = list(combinations(range(n), 2))
    edge_index = {edge: i for i, edge in enumerate(edge_list)}
    width = len(edge_list)
    maps = []
    for k in range(n-1):
        permutation = list(range(n))
        permutation[k], permutation[k+1] = permutation[k+1], permutation[k]
        maps.append(tuple(width-1-edge_index[tuple(sorted((permutation[i], permutation[j])))]
                          for i, j in edge_list))
    canonical = [-1]*(1 << width)
    automorphisms = {}
    for start in range(1 << width):
        if canonical[start] >= 0:
            continue
        canonical[start] = start
        queue = [start]
        for code in queue:
            for mapping in maps:
                transformed = 0
                for source in mapping:
                    transformed = 2*transformed + ((code >> source) & 1)
                if canonical[transformed] < 0:
                    canonical[transformed] = start
                    queue.append(transformed)
                else:
                    require(canonical[transformed] == start, 'Overlapping orbits')
        require(factorial(n) % len(queue) == 0, 'Invalid orbit size')
        automorphisms[start] = factorial(n)//len(queue)
    require(len(automorphisms) == (1, 2, 4, 11, 34, 156)[n-1], 'Atlas size mismatch')
    return tuple(canonical), automorphisms


def canonical(n, code):
    return universe(n)[0][code]


def aut(n, code):
    return universe(n)[1][canonical(n, code)]


def keys(level):
    return [(n, code) for n in range(1, level+1) for code in universe(n)[1]]


def accumulate(target, key, value):
    target[key] = target.get(key, Q(0)) + value
    if not target[key]:
        target.pop(key)


def extension_equation(params, n, code, subset):
    """sum_alpha Aut(H+alpha) X_(H+alpha) - Aut(H) t X_H = 0."""
    v, k, lam, mu = params
    require(tuple(sorted(set(subset))) == tuple(subset) and len(subset) <= 2,
            'Invalid required-neighbor subset')
    require(all(type(i) is int and 0 <= i < n for i in subset), 'Subset outside template')
    if not subset:
        t = v-n
    elif len(subset) == 1:
        t = k-sum(adjacent(n, code, subset[0], j) for j in range(n))
    else:
        i, j = subset
        t = (lam if adjacent(n, code, i, j) else mu) - sum(
            adjacent(n, code, i, z)*adjacent(n, code, j, z) for z in range(n))
    out = {}
    accumulate(out, (n, canonical(n, code)), -aut(n, code)*t)
    for profile in product((0, 1), repeat=n):
        if all(profile[i] for i in subset):
            child = canonical(n+1, append_vertex(n, code, profile))
            accumulate(out, (n+1, child), aut(n+1, child))
    return out


def determinant(matrix):
    if not matrix:
        return Q(1)
    return sum((-1)**j*matrix[0][j]*determinant(
        [row[:j]+row[j+1:] for row in matrix[1:]]) for j in range(len(matrix)))


def inverse_by_minors(matrix):
    """Sylvester's criterion, then adjugate; no shared LDL/elimination code."""
    n = len(matrix)
    minors = [determinant([row[:k] for row in matrix[:k]]) for k in range(1, n+1)]
    require(all(x > 0 for x in minors), 'Anchor is not positive definite')
    inv = [[(-1)**(i+j)*determinant([
        row[:i]+row[i+1:] for row in matrix[:j]+matrix[j+1:]])/minors[-1]
        for j in range(n)] for i in range(n)]
    require(all(sum(matrix[i][k]*inv[k][j] for k in range(n)) == (i == j)
                for i in range(n) for j in range(n)), 'Adjugate inverse mismatch')
    return inv, minors


def spectrum(params, which):
    v, k, lam, mu = params
    discriminant = (lam-mu)**2 + 4*(k-mu)
    root = isqrt(discriminant)
    require(root > 0 and root*root == discriminant, 'This checker needs rational spectrum')
    r, s = Q(lam-mu+root, 2), Q(lam-mu-root, 2)
    f = (-k-(v-1)*s)/(r-s)
    g = v-1-f
    require(f.denominator == g.denominator == 1 and min(f, g) > 0, 'Invalid multiplicities')
    require(which in ('r', 's'), 'This checker needs embedding r or s')
    if which == 'r':
        dimension, off, diagonal, ones = int(f), Q(v)/(f*(r-s)), -Q(v)*s/(f*(r-s)), -(k-s)/(f*(r-s))
    else:
        dimension, off, diagonal, ones = int(g), -Q(v)/(g*(r-s)), Q(v)*r/(g*(r-s)), (k-r)/(g*(r-s))
    require(diagonal+ones == 1, 'Gram diagonal mismatch')
    require(off*k+diagonal+ones*v == 0, 'Gram trivial eigenspace mismatch')
    require(off*(s if which == 'r' else r)+diagonal == 0, 'Gram other eigenspace mismatch')
    require(off*(r if which == 'r' else s)+diagonal == Q(v, dimension), 'Gram positive eigenspace mismatch')
    return dimension, ones, ones+off


def sos_expansion(params, term):
    t, ell = term['anchor_size'], term['degree']
    require(type(t) is int and 1 <= t <= 4 and type(ell) is int and ell in (1, 2),
            'Only <=4 anchors and degrees 1,2 are audited here')
    code = read_graph(t, term['anchor_bits'])
    require(code == canonical(t, code), 'Anchor must use the canonical labeling')
    weights = tuple(map(Q, term['vector']))
    require(len(weights) == 1 << t, 'Wrong profile vector length')
    dimension, a, b = spectrum(params, term['embedding'])
    residual_dimension = dimension-t
    require(residual_dimension >= ell, 'Insufficient residual dimension')
    gram = [[Q(1) if i == j else b if adjacent(t, code, i, j) else a
             for j in range(t)] for i in range(t)]
    inv, minors = inverse_by_minors(gram)
    profiles = tuple(product((0, 1), repeat=t))
    vectors = [[b if bit else a for bit in profile] for profile in profiles]
    projection = [[sum(x*inv[i][j]*y for i, x in enumerate(u) for j, y in enumerate(w))
                   for w in vectors] for u in vectors]
    heights = [1-projection[i][i] for i in range(len(profiles))]
    out = {}
    anchor_aut = aut(t, code)
    for alpha, profile_x in enumerate(profiles):
        one_extension = append_vertex(t, code, profile_x)
        one_key = (t+1, canonical(t+1, one_extension))
        accumulate(out, one_key, Q(aut(*one_key), anchor_aut)*weights[alpha]**2*heights[alpha]**ell)
        for beta, profile_y in enumerate(profiles):
            for edge in (0, 1):
                two_extension = append_vertex(t+1, one_extension, profile_y+(edge,))
                two_key = (t+2, canonical(t+2, two_extension))
                z = (b if edge else a)-projection[alpha][beta]
                kernel = z if ell == 1 else (
                    residual_dimension*z*z-heights[alpha]*heights[beta])/(residual_dimension-1)
                accumulate(out, two_key, Q(aut(*two_key), anchor_aut)*weights[alpha]*weights[beta]*kernel)
    return out, {'embedding': term['embedding'], 'anchor_size': t, 'anchor_bits': term['anchor_bits'],
                 'degree': ell, 'dimension': dimension, 'residual_dimension': residual_dimension,
                 'nonedge_inner_product': str(a), 'edge_inner_product': str(b),
                 'leading_principal_minors': list(map(str, minors)),
                 'zero_height_profiles': [i for i, h in enumerate(heights) if h == 0],
                 'negative_height_profiles': [i for i, h in enumerate(heights) if h < 0]}


def verify(data):
    require(data['format'] == 'srg-raw-identity-v1', 'Wrong raw certificate format')
    params = tuple(data['parameters'])
    require(len(params) == 4 and all(type(x) is int for x in params), 'Noninteger parameters')
    v, k, lam, mu = params
    require(v >= 3 and 0 < k < v-1 and 0 <= lam < k and 0 < mu <= k, 'Invalid parameters')
    require((v-k-1)*mu == k*(k-lam-1), 'Invalid SRG relation')
    level = data['level']
    require(type(level) is int and 3 <= level <= min(v, 6), 'Unsupported level')
    constant = Q(data['constant'])
    require(constant < 0, 'Constant must be strictly negative')
    residual, anchors = {}, []
    for term in data['nonnegative_terms']:
        weight = Q(term['weight'])
        require(weight >= 0, 'Negative weight on a nonnegative term')
        if term['kind'] == 'sos':
            require(type(term['anchor_size']) is int and term['anchor_size']+2 <= level,
                    'SOS exceeds count level')
            row, diagnostic = sos_expansion(params, term)
            anchors.append(diagnostic)
        else:
            require(term['kind'] == 'count', 'Unknown nonnegative term')
            n = term['size']
            require(type(n) is int and 1 <= n <= level, 'Count exceeds level')
            code = read_graph(n, term['bits'])
            require(code == canonical(n, code), 'Noncanonical count')
            row = {(n, code): Q(1)}
        for key, value in row.items():
            accumulate(residual, key, weight*value)
    # Check every coefficient of: nonnegative side - c0 X_K1 - sum y_e E_e.
    accumulate(residual, (1, 0), -constant)
    for equation in data['zero_equations']:
        n = equation['size']
        require(type(n) is int and 1 <= n < level, 'Extension exceeds count level')
        code = read_graph(n, equation['bits'])
        require(code == canonical(n, code), 'Noncanonical equation template')
        row = extension_equation(params, n, code, tuple(equation['subset']))
        weight = Q(equation['multiplier'])  # Equality multipliers may have either sign.
        for key, value in row.items():
            accumulate(residual, key, -weight*value)
    require(not residual, f'Raw polynomial identity fails at {next(iter(residual), None)}')
    return {'verified': True, 'parameters': list(params), 'constant': str(constant),
            'raw_count_variables': len(keys(level)), 'nonzero_residual_coefficients': len(residual),
            'nonnegative_terms': len(data['nonnegative_terms']), 'zero_equations': len(data['zero_equations']),
            'anchor_checks': anchors, 'arithmetic': 'fractions.Fraction; exact',
            'method': 'binary-profile extension; adjacent-transposition orbits; adjugate inverse; no elimination'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('files', nargs='+', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    reports = []
    for path in args.files:
        raw = path.read_bytes()
        report = {'file': str(path), 'sha256': sha256(raw).hexdigest(), **verify(json.loads(raw))}
        reports.append(report)
        print(json.dumps({k: value for k, value in report.items() if k != 'anchor_checks'}), flush=True)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(reports, indent=2)+'\n')


if __name__ == '__main__':
    main()
